/* Browser checks against the isolated real-template fixture; no live WordPress or GHL. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
(async function () {
    const browser = await chromium.launch({ headless: true, channel: process.env.HTR_BROWSER_CHANNEL || undefined });
    try {
        const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto(pathToFileURL(path.join(__dirname, '.floating-preview.html')).href);
        const preview = page.locator('[data-preview]');
        assert.equal(await preview.locator('.htr-floating__item').count(), 4);
        const output = path.resolve(__dirname, '../../../../reports/floating-tab');
        fs.mkdirSync(output, { recursive: true });
        await page.screenshot({ path: path.join(output, 'settings-desktop.png'), fullPage: true });
        await page.locator('[name=floating_style]').selectOption('expandable');
        await preview.locator('.htr-floating__toggle').focus();
        assert.equal(await preview.locator('.htr-floating__toggle').getAttribute('aria-expanded'), 'true');
        await preview.locator('.htr-floating__item').first().focus();
        await page.keyboard.press('Escape');
        assert.equal(await preview.locator('.htr-floating__toggle').getAttribute('aria-expanded'), 'false');
        await page.locator('[name=floating_behavior]').selectOption('click');
        await preview.locator('.htr-floating__toggle').click();
        assert.equal(await preview.locator('.htr-floating__toggle').getAttribute('aria-expanded'), 'true');
        await page.locator('[data-tab=items]').click();
        await page.locator('[data-add]').click();
        assert.equal(await page.locator('[data-items] [data-item]').count(), 5);
        await page.locator('[data-items] [data-item]').last().locator('[data-remove]').click();
        assert.equal(await page.locator('[data-items] [data-item]').count(), 4);
        await page.locator('[data-items] [data-item]').first().locator('[data-move=down]').click();
        assert.equal(await page.locator('[data-items] [name$="[label]"]').first().inputValue(), 'Our team');
        await page.locator('[name=floating_page]').selectOption('10');
        await page.locator('[data-tab=general]').click();
        await page.locator('[name=floating_style]').selectOption('quote');
        assert.equal(await preview.locator('.htr-floating__tab').count(), 1);
        await preview.locator('.htr-floating__close').click();
        assert.equal(await preview.locator('[data-htr-floating-message]').isVisible(), false);
        await page.locator('[name=floating_open_mode]').selectOption('drawer');
        await page.locator('[name=floating_drawer_form]').selectOption('calculator');
        await preview.locator('.htr-floating__tab').click();
        const drawer = page.locator('[data-htr-preview-drawer]');
        assert.equal(await drawer.evaluate(el => el.open), true);
        assert.match(await drawer.textContent(), /Roof Calculator/);
        await page.keyboard.press('Escape');
        assert.equal(await drawer.evaluate(el => el.open), false);
        await page.waitForFunction(() => document.body.style.overflow !== 'hidden');
        assert.equal(await page.evaluate(() => document.body.style.overflow), '');
        assert.equal(await preview.locator('.htr-floating__tab').evaluate(el => el === document.activeElement), true);
        await page.locator('[name=floating_style]').selectOption('icon_stack');
        await page.locator('button[data-device=mobile]').click();
        await page.locator('[name=floating_mobile]').uncheck();
        assert.equal(await preview.locator('[data-htr-floating]').isVisible(), false);
        await page.locator('[name=floating_mobile]').check();
        assert.equal(await preview.locator('[data-htr-floating]').isVisible(), true);
        await page.setViewportSize({ width: 375, height: 850 });
        await page.locator('[name=floating_style]').selectOption('quote');
        await preview.locator('.htr-floating__tab').click();
        const drawerWidth = await drawer.evaluate(el => el.getBoundingClientRect().width);
        assert.ok(drawerWidth <= 376, 'Mobile drawer width: ' + drawerWidth);
        await drawer.locator('[data-drawer-close]').click();
        await page.locator('[name=floating_style]').selectOption('icon_stack');
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Admin should not overflow mobile viewport');
        const sceneBounds = await page.locator('[data-scene]').boundingBox();
        const cardBounds = await page.locator('.htr-ft-preview-column .htr-ft-card').first().boundingBox();
        assert.ok(sceneBounds.x + sceneBounds.width <= cardBounds.x + cardBounds.width, 'Mobile preview stays inside its card');
        await page.screenshot({ path: path.join(output, 'settings-mobile.png'), fullPage: true });
        // Test the actual PHP-rendered drawer with a deliberately delayed iframe response.
        let release;
        const ready = new Promise(resolve => { release = resolve; });
        await page.route('https://example.test/**', async route => { await ready; await route.fulfill({ contentType: 'text/html', body: '<html><body>Fixture form ready</body></html>' }); });
        await page.evaluate(() => {
            const tab = document.createElement('aside');
            tab.className = 'htr-floating htr-floating--right';
            tab.dataset.htrFloating = ''; tab.dataset.openMode = 'drawer';
            const link = document.createElement('a'); link.className = 'htr-floating__tab'; link.href = 'https://example.test/?htr_rr_drawer=report'; link.textContent = 'Open test form';
            tab.append(link); document.body.append(tab); window.HTRFloatingTab.init(tab);
        });
        await page.getByRole('link', { name: 'Open test form', exact: true }).click();
        const realDrawer = page.locator('[data-htr-drawer]');
        assert.equal(await realDrawer.locator('.htr-drawer__loading').isVisible(), true);
        assert.equal(await realDrawer.locator('iframe').isVisible(), false);
        release();
        await realDrawer.locator('.htr-drawer__loading').waitFor({ state: 'hidden' });
        assert.equal(await realDrawer.locator('iframe').isVisible(), true);
        assert.equal(await realDrawer.locator('.htr-drawer__body').getAttribute('aria-busy'), 'false');
        await realDrawer.locator('[data-drawer-close]').click();
        await page.getByRole('link', { name: 'Open test form', exact: true }).click();
        assert.equal(await realDrawer.locator('.htr-drawer__loading').isVisible(), false);
        await realDrawer.locator('[data-drawer-close]').click();
        assert.deepEqual(errors, []);
        console.log('Floating settings browser checks passed: layouts, preview, keyboard, reorder, mobile and no JS errors.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
